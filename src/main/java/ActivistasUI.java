    private void mostrarDatos() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Ap. Paterno");
        modelo.addColumn("Ap. Materno");
        modelo.addColumn("Teléfono");
        modelo.addColumn("Fecha Inicio");

        tblActivistas.setModel(modelo);

        List<Activista> lista = activistaDAO.consultarTodos();

        for (Activista a : lista) {
            Object[] fila = new Object[6];
            fila[0] = a.getId();
            fila[1] = a.getNombre();
            fila[2] = a.getApellidoPaterno();
            fila[3] = a.getApellidoMaterno();
            fila[4] = a.getTelefono();
            fila[5] = a.getFechaInicio();
            modelo.addRow(fila);
        }
    }
    
