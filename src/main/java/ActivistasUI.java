    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // Extraer datos de los JTextField
        String nombre = txtNombre.getText();
        String apPaterno = txtApPaterno.getText();
        String apMaterno = txtApMaterno.getText();
        String telefono = txtTelefono.getText();
        LocalDate fecha = LocalDate.parse(txtFecha.getText()); // Asegura el formato yyyy-MM-dd

        Activista a = new Activista(nombre, apPaterno, apMaterno, telefono, fecha);
        activistaDAO.agregar(a);

        mostrarDatos(); // Refrescar tabla
        limpiar(); // Limpiar campos
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void tblActivistasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblActivistasMouseClicked
        int fila = tblActivistas.getSelectedRow();
    
        // Guardar ID seleccionado
        idSeleccionado = Integer.parseInt(tblActivistas.getValueAt(fila, 0).toString());

        // Llenar campos
        txtNombre.setText(tblActivistas.getValueAt(fila, 1).toString());
        txtApPaterno.setText(tblActivistas.getValueAt(fila, 2).toString());
        txtApMaterno.setText(tblActivistas.getValueAt(fila, 3) != null ? tblActivistas.getValueAt(fila, 3).toString() : "");
        txtTelefono.setText(tblActivistas.getValueAt(fila, 4).toString());
        txtFecha.setText(tblActivistas.getValueAt(fila, 5).toString());
    }//GEN-LAST:event_tblActivistasMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idSeleccionado != -1) {
        Activista a = new Activista(
            idSeleccionado, // Usamos el ID de la tabla
            txtNombre.getText(),
            txtApPaterno.getText(),
            txtApMaterno.getText(),
            txtTelefono.getText(),
            LocalDate.parse(txtFecha.getText())
        );
        activistaDAO.actualizar(a);
        mostrarDatos();
        limpiar();
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idSeleccionado != -1) {
        activistaDAO.eliminar(idSeleccionado);
        mostrarDatos();
        limpiar();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

